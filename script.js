function downloadComplaint() {

    const { jsPDF } = window.jspdf;

    const doc = new jsPDF();

    const category = localStorage.getItem("category") || "Not Provided";
    const date = localStorage.getItem("date") || "Not Provided";
    const location = localStorage.getItem("location") || "Not Provided";
    const description = localStorage.getItem("description") || "Not Provided";
    const caseID = localStorage.getItem("caseID") || "Not Generated";

    doc.setFontSize(20);
    doc.text("SafeSpeak", 20, 20);

    doc.setFontSize(16);
    doc.text("Anonymous Complaint Report", 20, 35);

    doc.setFontSize(12);

    doc.text("Case ID: " + caseID, 20, 50);
    doc.text("Category: " + category, 20, 60);
    doc.text("Incident Date: " + date, 20, 70);
    doc.text("Location: " + location, 20, 80);

    doc.text("Description:", 20, 95);

    const lines = doc.splitTextToSize(description, 170);
    doc.text(lines, 20, 105);

    doc.text("Generated by SafeSpeak", 20, 260);

    doc.save("SafeSpeak_Complaint.pdf");

}
function trackReport() {

    const enteredID = document.getElementById("caseInput").value.trim();

    const savedID = localStorage.getItem("caseID");

    const statusBox = document.getElementById("statusBox");
    const statusText = document.getElementById("statusText");

    if (enteredID === "") {
        alert("Please enter your Case ID.");
        return;
    }

    statusBox.style.display = "block";

    if (enteredID === savedID) {

        statusText.innerHTML = `
        <strong>Case ID:</strong> ${savedID}<br><br>
        ✅ Complaint Submitted<br>
        🕒 Under Review<br>
        🔒 Identity Protected
        `;

    } else {

        statusText.innerHTML = `
        ❌ No complaint found with this Case ID.
        `;

    }

}

   
