function generatePDF() {

    const category = localStorage.getItem("category") || "Not Provided";
    const date = localStorage.getItem("date") || "Not Provided";
    const location = localStorage.getItem("location") || "Not Provided";
    const description = localStorage.getItem("description") || "No description";

    const report = `
SAFESPEAK
Anonymous Incident Report

-------------------------------------

Case Type:
${category}

Date of Incident:
${date}

Location:
${location}

Incident Description:

${description}

-------------------------------------

Generated by SafeSpeak
Identity Protected

Generated On:
${new Date().toLocaleString()}
`;

    const blob = new Blob([report], {
        type: "text/plain"
    });

    const link = document.createElement("a");

    link.href = URL.createObjectURL(blob);

    link.download = "SafeSpeak_Report.txt";

    document.body.appendChild(link);

    link.click();

    document.body.removeChild(link);

    // Go to success page
    window.location.href = "success.html";
}
function generateCaseID() {

    let id = localStorage.getItem("caseID");

    if (!id) {
        id = "SS-" + Math.floor(100000 + Math.random() * 900000);
        localStorage.setItem("caseID", id);
    }

    document.getElementById("caseID").innerHTML =
        "Case ID: " + id;
}

function startListening() {

    if (!('webkitSpeechRecognition' in window)) {
        alert("Your browser doesn't support voice recognition.\nPlease open SafeSpeak in Google Chrome.");
        return;
    }

    const recognition = new webkitSpeechRecognition();

    recognition.lang = "en-US";
    recognition.continuous = false;
    recognition.interimResults = false;

    recognition.start();

    recognition.onstart = function () {
        alert("🎤 Listening... Speak now.");
    };

    recognition.onresult = function(event) {
        document.getElementById("description").value =
            event.results[0][0].transcript;
    };

    recognition.onerror = function() {
        alert("Voice recognition failed.");
    };
}


